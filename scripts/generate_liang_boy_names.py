def reduce81(n: int) -> int:
    while n > 81:
        n -= 80
    return n


def fortune(n: int) -> str:
    n = reduce81(n)
    if n in JI:
        return "吉"
    if n in BAN_JI:
        return "半吉"
    return "凶"


def num_wuxing(n: int) -> str:
    d = reduce81(n) % 10
    if d in (1, 2):
        return "木"
    if d in (3, 4):
        return "火"
    if d in (5, 6):
        return "土"
    if d in (7, 8):
        return "金"
    return "水"


def load_strokes(cc: OpenCC) -> Dict[str, int]:
    """优先本地 JSON；否则从康熙表构建。"""
    import json

    if STROKE_JSON.exists():
        raw = json.loads(STROKE_JSON.read_text(encoding="utf-8"))
        # map both simplified keys and traditional forms
        data: Dict[str, int] = {}
        for ch, info in raw.items():
            data[ch] = int(info["strokes"])
            data[info["trad"]] = int(info["strokes"])
        return data

    path = KANGXI_CSV if KANGXI_CSV.exists() else KANGXI_FALLBACK
    if not path.exists():
        import urllib.request

        KANGXI_CSV.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(KANGXI_URL, KANGXI_CSV)
        path = KANGXI_CSV

    data = {}
    with path.open(encoding="utf-8-sig", newline="") as f:
        while True:
            pos = f.tell()
            line = f.readline()
            if not line:
                break
            if "CodePoint" in line:
                f.seek(pos)
                break
        for row in csv.DictReader(f):
            data[row["Character"]] = int(row["Strokes"])
    return data


def build_charset(strokes: Dict[str, int], cc: OpenCC) -> Dict[str, CharInfo]:
    out: Dict[str, CharInfo] = {}
    for ch, wx, meaning in BOY_CHARS:
        if ch in out:
            continue
        if any(tag in meaning for tag in ("少用", "不宜", "忌", "慎用")):
            continue
        trad = cc.convert(ch)
        st = strokes.get(trad, strokes.get(ch))
        if st is None:
            print(f"WARN: missing strokes for {ch}/{trad}")
            continue
        out[ch] = CharInfo(ch=ch, trad=trad, strokes=st, wuxing=wx, meaning=meaning)
    return out


def calc_wuge(sur: int, a: int, b: int) -> Dict[str, int]:
    return {
        "天格": sur + 1,
        "人格": sur + a,
        "地格": a + b,
        "外格": b + 1,
        "总格": sur + a + b,
    }


